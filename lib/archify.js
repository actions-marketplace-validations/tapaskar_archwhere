'use strict';
// Compile the model into Archify IR (https://github.com/tt-a1i/archify):
// one system diagram (lanes, boundaries, guided views per flow) plus one
// numbered dynamic-view diagram per flow. Validated against Archify's
// published schemas in this repo's tests.

const fs = require('fs');
const path = require('path');
const W = require('./where');

const TYPE = { product: 'frontend', core: 'backend', feature: 'backend', security: 'security', infra: 'cloud' };
const aType = c => c.archifyType || TYPE[c.kind] || 'backend';

function systemIR(arch) {
  const LANES = W.lanesOf(arch).filter(l => l.some(id => TYPE[(arch.components[id] || {}).kind]));
  const titles = W.laneTitles(arch);
  const include = new Set(LANES.flat().filter(id => arch.components[id]));
  const cols = Math.max(...LANES.map(l => l.length), 1);
  const components = [];
  LANES.forEach((lane, row) => {
    const offset = Math.floor((cols - lane.length) / 2);
    lane.forEach((id, i) => {
      const c = arch.components[id]; if (!c) return;
      components.push({ id, type: aType(c), label: c.name, sublabel: c.sublabel || '', tag: c.kind, row, col: i + offset });
    });
  });
  const connections = [];
  for (const [id, c] of Object.entries(arch.components)) {
    if (!include.has(id)) continue;
    for (const d of c.deps || []) {
      if (!include.has(d)) continue;
      const sec = c.kind === 'security' || arch.components[d].kind === 'security';
      connections.push({ id: `${id}-${d}`, from: id, to: d, variant: sec ? 'security' : 'default' });
    }
  }
  const views = Object.entries(arch.flows || {}).slice(0, 4).map(([fid, f]) => ({
    id: `flow-${fid}`, label: f.name.slice(0, 48),
    focus: [...new Set(f.steps.flatMap(s => [s.from, s.to]))].filter(x => include.has(x)),
    note: (f.actor || '').slice(0, 140)
  })).filter(v => v.focus.length);
  const securityIds = [...include].filter(id => arch.components[id].kind === 'security');
  if (securityIds.length && views.length < 5) {
    views.push({ id: 'security-zones', label: 'Security zones', focus: securityIds, note: 'Review-sensitive components.' });
  }
  const boundaries = LANES.map((lane, i) => ({
    kind: lane.some(id => arch.components[id].kind === 'security') ? 'security-group' : 'region',
    label: titles[i] || `Lane ${i + 1}`,
    wraps: lane.filter(id => include.has(id))
  })).filter(b => b.wraps.length);
  return {
    schema_version: 1, diagram_type: 'architecture',
    meta: {
      title: `${W.systemName(arch)} — system architecture`,
      subtitle: 'Generated by archwhere from the declared model',
      output: 'system.html',
      visual_preset: 'signal-flow', animation: 'trace', quality_profile: 'showcase',
      legend: { mode: 'auto' }, views: views.slice(0, 5)
    },
    layout: { mode: 'grid', cols, gapX: 56, gapY: 84, cellW: 164, cellH: 58 },
    components, boundaries, connections
  };
}

function flowIR(arch, fid, f) {
  const ids = [...new Set(f.steps.flatMap(s => [s.from, s.to]))];
  const components = ids.map((id, i) => {
    const c = arch.components[id];
    if (!c) throw new Error(`flow ${fid} references unknown component: ${id}`);
    return { id, type: aType(c), label: c.name, sublabel: c.sublabel || '', tag: c.kind, row: i % 2, col: Math.floor(i / 2) };
  });
  const connections = f.steps.map((s, i) => ({
    id: `s${i + 1}`, from: s.from, to: s.to, label: `${i + 1}. ${s.label}`,
    variant: i === 0 ? 'emphasis' : 'default'
  }));
  return {
    schema_version: 1, diagram_type: 'architecture',
    meta: {
      title: f.name, subtitle: `Process flow · actor: ${f.actor || 'n/a'}`, output: `flow-${fid}.html`,
      visual_preset: 'signal-flow', animation: 'trace', quality_profile: 'showcase', legend: { mode: 'auto' }
    },
    layout: { mode: 'grid', cols: Math.max(2, Math.ceil(ids.length / 2)), gapX: 120, gapY: 110, cellW: 180, cellH: 60 },
    components, connections
  };
}

function emit(arch, outDir) {
  fs.mkdirSync(outDir, { recursive: true });
  const written = [];
  const w = (name, doc) => {
    const p = path.join(outDir, name);
    fs.writeFileSync(p, JSON.stringify(doc, null, 2) + '\n');
    written.push(p);
  };
  w('system.architecture.json', systemIR(arch));
  for (const [fid, f] of Object.entries(arch.flows || {})) w(`flow-${fid}.architecture.json`, flowIR(arch, fid, f));
  return written;
}

module.exports = { systemIR, flowIR, emit };
